/** Lightweight date helpers — replaces moment for the few call sites we need. */

export function addMinutes(isoLocal: string, minutes: number): string {
  const date = new Date(isoLocal);
  date.setMinutes(date.getMinutes() + minutes);
  return date.toISOString();
}

export function formatYmd(date: Date): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

export function formatDmY(date: Date): string {
  const d = String(date.getDate()).padStart(2, "0");
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const y = date.getFullYear();
  return `${d}.${m}.${y}`;
}

export function startOfDay(date: Date): Date {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
}

export function isSameDay(a: Date, b: Date): boolean {
  return (
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
  );
}

export function parseLocalDateTime(ymd: string, time: string): Date {
  return new Date(`${ymd}T${time}:00`);
}
